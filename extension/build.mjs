import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname);
const out = resolve(root, "dist");
const repoRoot = resolve(root, "..");
const publicDir = resolve(repoRoot, "public");

// Build-time origins. Override with env vars; defaults point at the live deploy.
const APP_ORIGIN = process.env.SAYLIENT_APP_ORIGIN || "https://saylient-ai.vercel.app";
const API_BASE = process.env.SAYLIENT_API_BASE || "https://saylient-ai-backend.onrender.com/api/v1";
const API_ORIGIN = new URL(API_BASE).origin;

// Pages the content script runs on: every HTTPS page (screen analysis),
// plus the local dev origins.
const PAGE_MATCHES = ["https://*/*", "http://localhost/*", "http://127.0.0.1/*"];
const HOST_PERMISSIONS = [...PAGE_MATCHES, `${API_ORIGIN}/*`];

const manifest = {
  manifest_version: 3,
  name: "Saylient AI — Communication Assistant",
  version: "0.1.0",
  description:
    "Click the icon to open Saylient AI, or analyze the text on any page with real backend analysis — only when you click Analyze. Nothing is monitored or sent automatically.",
  permissions: ["storage", "activeTab", "contextMenus", "scripting"],
  host_permissions: HOST_PERMISSIONS,
  web_accessible_resources: [{ resources: ["content.css"], matches: PAGE_MATCHES }],
  // No default_popup: clicking the toolbar icon opens the hero page
  // (background.js, chrome.action.onClicked).
  action: { default_title: "Open Saylient AI" },
  background: { service_worker: "background.js" },
  content_scripts: [
    {
      matches: PAGE_MATCHES,
      js: ["config.js", "content.js"],
      css: ["content.css"],
      run_at: "document_idle",
    },
  ],
  icons: { "16": "icon.svg", "48": "icon.svg", "128": "icon.svg" },
};

// Generated runtime config, shared by popup.js, content.js and background.js.
const config = `// Generated by build.mjs — do not edit by hand.
// Override with SAYLIENT_APP_ORIGIN / SAYLIENT_API_BASE env vars at build time.
const SAYLIENT_APP_ORIGIN = ${JSON.stringify(APP_ORIGIN)};
const SAYLIENT_API_BASE = ${JSON.stringify(API_BASE)};
`;

// --- Minimal stored (uncompressed) ZIP writer, stdlib only. -----------
// No `zip` binary is needed, so the build works on any machine. Chrome
// installs stored entries exactly like deflated ones.
const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function dosDateTime(date) {
  return {
    time: ((date.getHours() & 0x1f) << 11) | ((date.getMinutes() & 0x3f) << 5) | ((Math.floor(date.getSeconds() / 2)) & 0x1f),
    date: (((date.getFullYear() - 1980) & 0x7f) << 9) | (((date.getMonth() + 1) & 0xf) << 5) | (date.getDate() & 0x1f),
  };
}

async function listFiles(dir, base = "") {
  const entries = await readdir(resolve(dir, base), { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listFiles(dir, rel)));
    else if (entry.isFile()) files.push(rel);
  }
  return files;
}

async function writeZip(zipPath, dir) {
  const files = await listFiles(dir);
  const { time, date } = dosDateTime(new Date());
  const chunks = [];
  const central = [];
  let offset = 0;
  for (const rel of files) {
    const data = await readFile(resolve(dir, rel));
    const name = Buffer.from(rel, "utf8");
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // flags: UTF-8 file names
    local.writeUInt16LE(0, 8); // method: stored (no compression)
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    chunks.push(local, name, data);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4); // version made by
    entry.writeUInt16LE(20, 6); // version needed
    entry.writeUInt16LE(0x0800, 8);
    entry.writeUInt16LE(0, 10);
    entry.writeUInt16LE(time, 12);
    entry.writeUInt16LE(date, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(data.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(name.length, 28);
    entry.writeUInt16LE(0, 30); // extra field length
    entry.writeUInt16LE(0, 32); // comment length
    entry.writeUInt16LE(0, 34); // disk number
    entry.writeUInt16LE(0, 36); // internal attributes
    entry.writeUInt32LE(0, 38); // external attributes
    entry.writeUInt32LE(offset, 42);
    central.push(entry, name);
    offset += local.length + name.length + data.length;
  }
  const centralStart = offset;
  const centralSize = central.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(centralStart, 16);
  end.writeUInt16LE(0, 20);
  await mkdir(publicDir, { recursive: true });
  await writeFile(zipPath, Buffer.concat([...chunks, ...central, end]));
  return files.length;
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(resolve(root, "src"), out, { recursive: true });
await writeFile(resolve(out, "config.js"), config);
await writeFile(resolve(root, "src", "config.js"), config);
await writeFile(resolve(out, "manifest.json"), JSON.stringify(manifest, null, 2));

// Keep the checked-in copies at the extension root and the repo root in sync.
for (const file of [
  "manifest.json",
  "config.js",
  "background.js",
  "content.js",
  "content.css",
  "icon.svg",
  "popup.html",
  "popup.css",
  "popup.js",
]) {
  await cp(resolve(out, file), resolve(root, file));
  await cp(resolve(out, file), resolve(root, "..", file));
}

// Downloadable build: a zip of extension/dist in the frontend public dir,
// so the deployed site serves it at /saylient-extension.zip.
const zipPath = resolve(publicDir, "saylient-extension.zip");
const zipCount = await writeZip(zipPath, out);

console.log(`Built extension to ${out}`);
console.log(`App origin: ${APP_ORIGIN}`);
console.log(`API base:   ${API_BASE}`);
console.log(`Wrote ${zipPath} (${zipCount} files) — served at /saylient-extension.zip`);
